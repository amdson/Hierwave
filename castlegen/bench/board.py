"""Leaderboard: the latest run per (variant, problem) from results/bench.jsonl.  FROZEN."""
from __future__ import annotations

import json

from .run import ROOT, harness_hash


def _mark(ok):
    return "–" if ok is None else ("ok" if ok else "FAIL")


def _blocks(r):
    """(rho string, starved string) from the block check, levels 0..T, direct weight (subtree in
    brackets); n/a when a seed has none.  Mean over seeds."""
    bs = [m.get("blocks") for m in r["per_seed"]]
    if not bs or any(b is None for b in bs):
        return "n/a", "n/a"
    rho, st = [], []
    for l in sorted(bs[0]["levels"], key=int):
        def mean(key, w):
            vals = [b["levels"][l][w][key] for b in bs if b["levels"][l][w][key] is not None]
            return sum(vals) / len(vals) if vals else None
        f = lambda v, fmt: "–" if v is None else format(v, fmt)
        rho.append(f"{f(mean('rho_pool', 'direct'), '.2f')} [{f(mean('rho_pool', 'subtree'), '.2f')}]")
        st.append(f"{f(None if mean('starved_probe', 'direct') is None else 100 * mean('starved_probe', 'direct'), '.0f')} "
                  f"[{f(None if mean('starved_probe', 'subtree') is None else 100 * mean('starved_probe', 'subtree'), '.0f')}]")
    return " / ".join(rho), " / ".join(st)


def board(path=None):
    path = path or ROOT / "results" / "bench.jsonl"
    latest = {}
    for line in open(path):
        r = json.loads(line)
        latest[(r["variant"], r["problem"])] = r
    cur = harness_hash()
    rows = ["| variant | problem | accepted | final viol (worst) | raw viol (worst) | free energy / cell | exact | raw≈final | seeds agree | probes | rho per level (pool) | starved % per level (probe blocks) | support | train s | gen s/world | run |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for (var, prob), r in sorted(latest.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        v = r["verdict"]
        fe = v["free_energy"]
        stale = "" if r["harness"] == cur else " (old harness)"
        gen = sum(m["gen_s_per_world"] for m in r["per_seed"]) / len(r["per_seed"])
        rho, stv = _blocks(r)
        rows.append(
            f"| {var} | {prob} v{r['problem_version']} | {'**yes**' if v['accepted'] else 'no'} | "
            f"{v['final_violations']['worst_frac']:.2e} | {v['raw_violations_worst']:.2e} | "
            f"{'–' if fe is None else f'{fe:.4f}'} | {_mark(v['exact_stats']['ok'])} | "
            f"{_mark(v['raw_vs_final']['ok'])} | {_mark(v['across_seeds']['ok'])} | {_mark(v['probes']['ok'])} | {rho} | {stv} | "
            f"{_mark(v['finite_support']['ok'])} | {r['train_budget_s']:.0f} | {gen:.2f} | {r['run']}{stale} |")
    text = "# Coloured-pass benchmark\n\nLatest run per variant and problem. Generated by `python -m castlegen.bench board`; do not edit. Bench version 2 adds the block check (not an acceptance gate): rho = Spearman between block log q share and direct target log-weight share [subtree weight], levels 0 / 1 / ... / T; starved = % of probe blocks more than 5 nats below the own-draw line, same order; n/a = older run or no per-draw log q.\n\n" + "\n".join(rows) + "\n"
    out = ROOT / "results" / "board.md"
    out.write_text(text)
    return text
