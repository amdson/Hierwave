"""Leaderboard: the latest run per (variant, problem) from results/bench.jsonl.  FROZEN."""
from __future__ import annotations

import json

from .run import ROOT, harness_hash


def _mark(ok):
    return "–" if ok is None else ("ok" if ok else "FAIL")


def board(path=None):
    path = path or ROOT / "results" / "bench.jsonl"
    latest = {}
    for line in open(path):
        r = json.loads(line)
        latest[(r["variant"], r["problem"])] = r
    cur = harness_hash()
    rows = ["| variant | problem | accepted | final viol (worst) | raw viol (worst) | free energy / cell | exact | raw≈final | seeds agree | probes | support | train s | gen s/world | run |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for (var, prob), r in sorted(latest.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        v = r["verdict"]
        fe = v["free_energy"]
        stale = "" if r["harness"] == cur else " (old harness)"
        gen = sum(m["gen_s_per_world"] for m in r["per_seed"]) / len(r["per_seed"])
        rows.append(
            f"| {var} | {prob} v{r['problem_version']} | {'**yes**' if v['accepted'] else 'no'} | "
            f"{v['final_violations']['worst_frac']:.2e} | {v['raw_violations_worst']:.2e} | "
            f"{'–' if fe is None else f'{fe:.4f}'} | {_mark(v['exact_stats']['ok'])} | "
            f"{_mark(v['raw_vs_final']['ok'])} | {_mark(v['across_seeds']['ok'])} | {_mark(v['probes']['ok'])} | "
            f"{_mark(v['finite_support']['ok'])} | {r['train_budget_s']:.0f} | {gen:.2f} | {r['run']}{stale} |")
    text = "# Coloured-pass benchmark\n\nLatest run per variant and problem. Generated by `python -m castlegen.bench board`; do not edit.\n\n" + "\n".join(rows) + "\n"
    out = ROOT / "results" / "board.md"
    out.write_text(text)
    return text
