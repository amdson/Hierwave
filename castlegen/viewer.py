"""Interactive 2D viewer for infinite tile worlds (castlegen/infinite.py).

A character walks the infinite tile plane (WASD / arrows, shift = fast); the
camera follows; +/- zoom (pixels per tile).  Chunks within the render
distance of the player are generated by one background worker thread, in
batches (the bounding rectangle of nearby missing chunks, grown greedily from
the missing chunk nearest the player) since a lone chunk pays ~30x padding.
The frame loop never waits for generation: it draws the chunks that exist,
ungenerated ones dark grey.

Keys: WASD / arrows move, shift x4 speed, + / - zoom, B chunk borders,
M wildcard overlay (city: id == T, magenta), H text line, Esc / Q quit.

Backends (region(y0, x0, H, W) -> int32 (H, W) array):
  numba  castlegen.infinite kernels, re-entered through nogil wrappers so the
         generating thread does not hold the GIL (the sampler stays
         single-core; the frame loop keeps running).  Bit-identical to
         infinite.generate.
  c      castlegen.hwsampler World(model, seed, C).region (thread A); falls
         back to numba with a printed note if missing or failing.

Launch:
  PYTHONPATH=. NUMBA_NUM_THREADS=1 uv run --extra viewer python -m castlegen.viewer [--set city]
"""
from __future__ import annotations

import argparse
import math
import os
import sys
import threading
import time

import numpy as np
from numba import njit

from castlegen import infinite as inf

DARK = (40, 40, 40)
MAGENTA = (255, 0, 255)
ZOOMS = [1, 2, 3, 4, 6, 8, 12, 16, 24, 32]
DATA_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "luanti", "games", "hierwave", "mods", "hierwave_gen", "data")


# ------------------------------------------------------------------ nogil kernels
# Thin wrappers: the callees are compiled into these entry points, which drop
# the GIL for the whole call.  Not cached (a cached wrapper would not notice
# changes in infinite.py and could silently go stale).
@njit(nogil=True)
def _anneal_ng(grid, gy0, gx0, seed, u, Eh, Ev, Hh, Hv, beta, gamma, ups):
    inf._anneal(grid, gy0, gx0, seed, u, Eh, Ev, Hh, Hv, beta, gamma, ups)


@njit(nogil=True)
def _anneal_sockets_ng(grid, gy0, gx0, seed, base, sN, sE, sS, sW, beta, gamma, ups, cone, fix):
    inf._anneal_sockets(grid, gy0, gx0, seed, base, sN, sE, sS, sW, beta, gamma, ups, cone, fix)


def _run_nogil(model, grid, gy0, gx0, seed, sched, ups):
    if isinstance(model, inf.SocketModel):
        base = np.exp(-sched.beta[:, None] * (model.u - model.u.min())[None, :])
        _anneal_sockets_ng(grid, gy0, gx0, seed, base, model.sN, model.sE, model.sS, model.sW,
                           sched.beta, sched.gamma, ups, True, model.wild_u is not None)
    elif isinstance(model, inf.TileModel):
        _anneal_ng(grid, gy0, gx0, seed, model.u, model.Eh, model.Ev, model.Hh, model.Hv,
                   sched.beta, sched.gamma, ups)
    else:                                       # unknown model: its own run (holds the GIL)
        model.run(grid, gy0, gx0, seed, sched, ups)


class NumbaBackend:
    """infinite.generate, GIL released during the kernel."""
    name = "numba"

    def __init__(self, model, sched, seed):
        self.model, self.sched, self.seed = model, sched, int(seed)
        self.stats = {}
        # compile the nogil wrappers here (compilation holds the GIL), not in the worker
        warm = inf.Schedule(self.sched.beta[:1], self.sched.gamma[:1])
        _run_nogil(model, np.zeros((5, 5), np.int32), np.int64(0), np.int64(0), np.uint64(0), warm,
                   np.zeros(1, np.int64))

    def region(self, y0, x0, H, W):
        P = self.sched.pad + getattr(self.model, "extra_pad", 0)
        grid = np.zeros((H + 2 * P, W + 2 * P), np.int32)
        ups = np.zeros(1, np.int64)
        _run_nogil(self.model, grid, np.int64(y0 - P), np.int64(x0 - P), np.uint64(self.seed & inf.M64),
                   self.sched, ups)
        self.stats["updates"] = self.stats.get("updates", 0) + int(ups[0])
        self.stats["cells"] = self.stats.get("cells", 0) + H * W
        return grid[P:P + H, P:P + W].copy()


class CBackend:
    name = "c"

    def __init__(self, world):
        self.world = world

    def region(self, y0, x0, H, W):
        return np.asarray(self.world.region(y0, x0, H, W), np.int32)


def make_c_backend(set_name, seed, C, fast=True):
    """hwsampler World for the exported model file; raises on any problem."""
    from castlegen import hwsampler
    path = os.path.join(DATA_DIR, f"{set_name}.hwm")
    if not os.path.exists(path):
        raise RuntimeError(f"{path} missing (python -m castlegen.export_models)")
    model = hwsampler.Model.load(path)
    if fast:
        model.set_fast()
    world = hwsampler.World(model, seed, C)
    probe = np.asarray(world.region(0, 0, 1, 1))
    if probe.shape != (1, 1):
        raise RuntimeError(f"hwsampler region returned shape {probe.shape}")
    return CBackend(world)


# ------------------------------------------------------------------ tile sets
class TileSetView:
    """model + schedule + atlas(px) -> (n_ids, px, px, 3) uint8 thumbnails,
    wild = wildcard id (None if no wildcard), names for the HUD."""

    def __init__(self, name, model, sched, atlas_fn, min_px, wild=None):
        self.name, self.model, self.sched = name, model, sched
        self._atlas_fn, self.min_px, self.wild = atlas_fn, min_px, wild
        self._atlases = {}

    def atlas(self, px):
        a = max(px, self.min_px)
        if a not in self._atlases:
            self._atlases[a] = self._atlas_fn(a)
        return self._atlases[a]


def biomes_view(S=64):
    m = inf.biomes()
    return TileSetView("biomes", m, inf.Schedule.anneal(S=S),
                       lambda px: np.broadcast_to(m.colors[:, None, None, :], (m.T, px, px, 3)).copy(), 1)


CITY_ZONE_W = {"P": 0.4, "R": 1.0, "C": 1.0, "D": 1.0, "I": 1.0, "W": 0.8, "A": 0.6}
CITY_BOUNDARY_W = 0.5


def city_tileset():
    """citytiles.TileSet with the contract weights; module globals restored."""
    from castlegen import citytiles as ct
    old = ct.BOUNDARY_W, dict(ct.ZONE_W)
    try:
        ct.BOUNDARY_W = CITY_BOUNDARY_W
        ct.ZONE_W = dict(CITY_ZONE_W)
        return ct.TileSet()
    finally:
        ct.BOUNDARY_W, ct.ZONE_W = old[0], old[1]


def city_view(S=64):
    from castlegen import citytiles as ct
    ts = city_tileset()
    m = inf.SocketModel(-np.log(ts.w), ts.sN, ts.sE, ts.sS, ts.sW, wild_u=20.0)
    T = ts.T

    def atlas(px):
        img = ct.render(ts, np.arange(T, dtype=np.int64)[None, :], px=px)      # (px, T px, 3)
        a = np.empty((T + 1, px, px, 3), np.uint8)
        a[:T] = img.reshape(px, T, px, 3).transpose(1, 0, 2, 3)
        a[T] = (170, 170, 175)                                                  # wildcard: plaza grey
        return a

    from castlegen.export_models import city_model
    return TileSetView("city", m, city_model()[1], atlas, 8, wild=T)


# ------------------------------------------------------------------ chunk store + worker
class ChunkStore:
    """Chunks (cy, cx) -> (C, C) int32, filled by one worker thread that
    repeatedly takes the nearest missing wanted chunk and grows a rectangle of
    missing chunks around it (max_batch chunks), generating it as one region."""

    def __init__(self, backend, C=32, render_distance=4, max_batch=16):
        self.backend, self.C, self.R, self.max_batch = backend, int(C), int(render_distance), int(max_batch)
        self.chunks = {}
        self.inflight = set()
        self.center = (0, 0)
        self.lock = threading.Lock()
        self.wake = threading.Event()
        self.stop_flag = False
        self.last_batch = None          # (seconds, rows, cols)
        self.batches = 0
        self.error = None
        self.thread = threading.Thread(target=self._loop, daemon=True, name="chunkgen")
        self.thread.start()

    def set_center(self, cy, cx):
        if (cy, cx) != self.center:
            self.center = (cy, cx)
            self.wake.set()

    def wanted(self):
        cy, cx = self.center
        R = self.R
        return [(cy + dy, cx + dx) for dy in range(-R, R + 1) for dx in range(-R, R + 1)]

    def missing(self):
        with self.lock:
            return [k for k in self.wanted() if k not in self.chunks and k not in self.inflight]

    def queue_len(self):
        return len(self.missing())

    def _next_job(self):
        with self.lock:
            cy, cx = self.center
            miss = {k for k in self.wanted() if k not in self.chunks and k not in self.inflight}
            if not miss:
                return None
            k0 = min(miss, key=lambda k: ((k[0] - cy) ** 2 + (k[1] - cx) ** 2, k))
            y0, y1, x0, x1 = k0[0], k0[0] + 1, k0[1], k0[1] + 1
            grew = True
            while grew:
                grew = False
                for d in range(4):
                    h, w = y1 - y0, x1 - x0
                    if d == 0:
                        new, n = [(y0 - 1, x) for x in range(x0, x1)], (h + 1) * w
                    elif d == 1:
                        new, n = [(y1, x) for x in range(x0, x1)], (h + 1) * w
                    elif d == 2:
                        new, n = [(y, x0 - 1) for y in range(y0, y1)], h * (w + 1)
                    else:
                        new, n = [(y, x1) for y in range(y0, y1)], h * (w + 1)
                    if n <= self.max_batch and all(k in miss for k in new):
                        if d == 0: y0 -= 1
                        elif d == 1: y1 += 1
                        elif d == 2: x0 -= 1
                        else: x1 += 1
                        grew = True
            keys = [(y, x) for y in range(y0, y1) for x in range(x0, x1)]
            self.inflight.update(keys)
            return y0, y1, x0, x1

    def _loop(self):
        C = self.C
        while not self.stop_flag:
            job = self._next_job()
            if job is None:
                self.wake.wait(0.05)
                self.wake.clear()
                continue
            y0, y1, x0, x1 = job
            t = time.perf_counter()
            try:
                g = self.backend.region(y0 * C, x0 * C, (y1 - y0) * C, (x1 - x0) * C)
            except Exception as e:                  # noqa: BLE001
                self.error = repr(e)
                print("viewer: generation failed:", self.error, file=sys.stderr)
                with self.lock:
                    self.inflight.difference_update((y, x) for y in range(y0, y1) for x in range(x0, x1))
                self.stop_flag = True
                return
            dt = time.perf_counter() - t
            with self.lock:
                for y in range(y0, y1):
                    for x in range(x0, x1):
                        self.chunks[(y, x)] = np.ascontiguousarray(g[(y - y0) * C:(y - y0 + 1) * C,
                                                                     (x - x0) * C:(x - x0 + 1) * C])
                        self.inflight.discard((y, x))
                self.last_batch = (dt, y1 - y0, x1 - x0)
                self.batches += 1

    def idle(self):
        return not self.missing() and not self.inflight

    def wait_idle(self, timeout=60.0):
        t = time.perf_counter() + timeout
        while time.perf_counter() < t:
            if self.error or self.idle():
                return self.idle()
            time.sleep(0.02)
        return False

    def stop(self):
        self.stop_flag = True
        self.wake.set()
        self.thread.join(timeout=120)


# ------------------------------------------------------------------ viewer
class Viewer:
    def __init__(self, tsv: TileSetView, backend, C=32, render_distance=4, px=4, size=(1024, 768),
                 max_batch=16, start=(0.0, 0.0)):
        import pygame
        self.pg = pygame
        self.tsv, self.C = tsv, int(C)
        self.store = ChunkStore(backend, C, render_distance, max_batch)
        self.backend_name = getattr(backend, "name", type(backend).__name__)
        self.py, self.px_ = float(start[0]), float(start[1])       # player, tile units
        self.zoom_i = ZOOMS.index(px) if px in ZOOMS else 3
        self.size = size
        self.show_borders, self.show_wild, self.show_hud = False, True, True
        self.surfs = {}             # (cy, cx) -> Surface at current px
        self.wild_pos = {}          # (cy, cx) -> (n, 2) positions of wildcards
        self.font = None
        self.fps = 0.0
        self._update_center()

    @property
    def px(self):
        return ZOOMS[self.zoom_i]

    def zoom(self, d):
        i = min(max(self.zoom_i + d, 0), len(ZOOMS) - 1)
        if i != self.zoom_i:
            self.zoom_i = i
            self.surfs.clear()

    def _update_center(self):
        self.store.set_center(math.floor(self.py) // self.C, math.floor(self.px_) // self.C)

    def move(self, dy, dx, dt, speed=24.0):
        n = math.hypot(dy, dx)
        if n > 0:
            self.py += dy / n * speed * dt
            self.px_ += dx / n * speed * dt
        self._update_center()

    def _chunk_surface(self, key, grid):
        pg = self.pg
        px = self.px
        at = self.tsv.atlas(px)
        a = at.shape[1]
        C = self.C
        img = at[grid].transpose(0, 2, 1, 3, 4).reshape(C * a, C * a, 3)
        s = pg.surfarray.make_surface(np.ascontiguousarray(img.swapaxes(0, 1)))
        if a != px:
            s = pg.transform.smoothscale(s, (C * px, C * px))
        if self.tsv.wild is not None and key not in self.wild_pos:
            self.wild_pos[key] = np.argwhere(grid == self.tsv.wild)
        return s

    def draw(self, screen, budget=8):
        """Draw the view; build at most `budget` new chunk surfaces."""
        pg = self.pg
        W, H = screen.get_size()
        px, C = self.px, self.C
        screen.fill((20, 20, 24))
        # world coord of screen pixel (0, 0)
        ox, oy = self.px_ - W / (2 * px), self.py - H / (2 * px)
        cx0, cx1 = math.floor(ox / C), math.floor((ox + W / px) / C)
        cy0, cy1 = math.floor(oy / C), math.floor((oy + H / px) / C)
        built = 0
        chunks = self.store.chunks
        for cy in range(cy0, cy1 + 1):
            for cx in range(cx0, cx1 + 1):
                sx = round((cx * C - ox) * px)
                sy = round((cy * C - oy) * px)
                key = (cy, cx)
                s = self.surfs.get(key)
                if s is None:
                    g = chunks.get(key)
                    if g is not None and built < budget:
                        s = self.surfs[key] = self._chunk_surface(key, g)
                        built += 1
                if s is None:
                    pg.draw.rect(screen, DARK, (sx, sy, C * px, C * px))
                else:
                    screen.blit(s, (sx, sy))
                    if self.show_wild and key in self.wild_pos:
                        for i, j in self.wild_pos[key]:
                            pg.draw.rect(screen, MAGENTA, (sx + j * px, sy + i * px, max(px, 2), max(px, 2)))
                if self.show_borders:
                    pg.draw.rect(screen, (255, 255, 0), (sx, sy, C * px, C * px), 1)
        # drop far surfaces
        if len(self.surfs) > 4 * (cy1 - cy0 + 3) * (cx1 - cx0 + 3):
            for k in [k for k in self.surfs if not (cy0 - 1 <= k[0] <= cy1 + 1 and cx0 - 1 <= k[1] <= cx1 + 1)]:
                del self.surfs[k]
        # player
        r = max(4, px // 2 + 2)
        c = (W // 2, H // 2)
        pg.draw.circle(screen, (0, 0, 0), c, r + 2)
        pg.draw.circle(screen, (255, 80, 60), c, r)
        if self.show_hud:
            self._hud(screen)

    def hud_text(self):
        st = self.store
        lb = st.last_batch
        lbs = f"{lb[0]:.2f} s ({lb[1]}x{lb[2]} chunks)" if lb else "-"
        return (f"{self.tsv.name}/{self.backend_name}  pos ({math.floor(self.py)}, {math.floor(self.px_)})  "
                f"chunk {st.center}  cached {len(st.chunks)}  queue {st.queue_len()}  "
                f"inflight {len(st.inflight)}  last batch {lbs}  px {self.px}  fps {self.fps:.0f}"
                + (f"  ERROR {st.error}" if st.error else ""))

    def _hud(self, screen):
        pg = self.pg
        if self.font is None:
            self.font = pg.font.SysFont("menlo,monospace", 14) if pg.font.get_init() else None
            if self.font is None:
                return
        t = self.font.render(self.hud_text(), True, (255, 255, 255))
        bg = pg.Surface((t.get_width() + 8, t.get_height() + 4))
        bg.set_alpha(170)
        bg.fill((0, 0, 0))
        screen.blit(bg, (4, 4))
        screen.blit(t, (8, 6))

    def handle_key(self, key):
        pg = self.pg
        if key in (pg.K_EQUALS, pg.K_PLUS, pg.K_KP_PLUS):
            self.zoom(1)
        elif key in (pg.K_MINUS, pg.K_KP_MINUS):
            self.zoom(-1)
        elif key == pg.K_b:
            self.show_borders = not self.show_borders
        elif key == pg.K_m:
            self.show_wild = not self.show_wild
        elif key == pg.K_h:
            self.show_hud = not self.show_hud

    def held_direction(self):
        pg = self.pg
        k = pg.key.get_pressed()
        dy = (k[pg.K_s] or k[pg.K_DOWN]) - (k[pg.K_w] or k[pg.K_UP])
        dx = (k[pg.K_d] or k[pg.K_RIGHT]) - (k[pg.K_a] or k[pg.K_LEFT])
        fast = 4.0 if (k[pg.K_LSHIFT] or k[pg.K_RSHIFT]) else 1.0
        return dy, dx, fast

    def run(self, frames=None, script=None, fps=60, screenshot=None):
        """Frame loop.  frames=None runs until quit; script(frame) -> (dy, dx)
        replaces the keyboard (headless)."""
        pg = self.pg
        screen = pg.display.set_mode(self.size, 0 if script else pg.RESIZABLE)
        pg.display.set_caption(f"hierwave viewer: {self.tsv.name}")
        clock = pg.time.Clock()
        f = 0
        try:
            while frames is None or f < frames:
                dt = clock.tick(fps) / 1000.0
                self.fps = clock.get_fps()
                for ev in pg.event.get():
                    if ev.type == pg.QUIT:
                        return
                    if ev.type == pg.KEYDOWN:
                        if ev.key in (pg.K_ESCAPE, pg.K_q):
                            return
                        self.handle_key(ev.key)
                    if ev.type == pg.VIDEORESIZE:
                        screen = pg.display.set_mode(ev.size, pg.RESIZABLE)
                if script is not None:
                    dy, dx = script(f)
                    fast = 1.0
                else:
                    dy, dx, fast = self.held_direction()
                self.move(dy, dx, dt, speed=24.0 * fast * 4 / self.px)
                self.draw(screen)
                pg.display.flip()
                f += 1
            if screenshot:
                self.store.wait_idle(120)
                self.surfs.clear()
                self.draw(screen, budget=10 ** 6)
                pg.image.save(screen, screenshot)
        finally:
            self.store.stop()


def make_backend(kind, tsv, seed, C, fast=True):
    if kind == "c":
        try:
            b = make_c_backend(tsv.name, seed, C, fast)
            print(f"viewer: C backend (hwsampler, {'fast' if fast else 'exact'}) for {tsv.name}")
            return b
        except Exception as e:                  # noqa: BLE001
            print(f"viewer: C backend unavailable ({e!r}); falling back to numba")
    return NumbaBackend(tsv.model, tsv.sched, seed)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--set", choices=["biomes", "city"], default="biomes")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--chunk", type=int, default=32)
    ap.add_argument("--render-distance", type=int, default=None,
                    help="chunks (Chebyshev) around the player; default 4 biomes, 2 city")
    ap.add_argument("--backend", choices=["numba", "c"], default="numba")
    ap.add_argument("--exact", action="store_true", help="C backend: exact (numba-identical) sampling instead of fast")
    ap.add_argument("--px", type=int, default=None, help="pixels per tile (default 4 biomes, 8 city)")
    ap.add_argument("--size", default="1024x768")
    ap.add_argument("--max-batch", type=int, default=16, help="max chunks per generation batch")
    ap.add_argument("--headless", action="store_true")
    ap.add_argument("--frames", type=int, default=None)
    ap.add_argument("--screenshot", default=None, help="save the last frame (after generation settles)")
    a = ap.parse_args(argv)
    if a.headless:
        os.environ["SDL_VIDEODRIVER"] = "dummy"
        os.environ.setdefault("SDL_AUDIODRIVER", "dummy")
    import pygame
    pygame.init()
    tsv = biomes_view() if a.set == "biomes" else city_view()
    backend = make_backend(a.backend, tsv, a.seed, a.chunk, fast=not a.exact)
    R = a.render_distance if a.render_distance is not None else (4 if a.set == "biomes" else 2)
    px = a.px or (4 if a.set == "biomes" else 8)
    w, h = (int(v) for v in a.size.split("x"))
    v = Viewer(tsv, backend, C=a.chunk, render_distance=R, px=px, size=(w, h), max_batch=a.max_batch)
    script = (lambda f: (0, 1)) if a.headless else None
    frames = a.frames if a.frames is not None else (120 if a.headless else None)
    v.run(frames=frames, script=script, screenshot=a.screenshot)
    print(v.hud_text())
    pygame.quit()


if __name__ == "__main__":
    main()
