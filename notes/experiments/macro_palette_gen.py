"""Writes castlegen/tilesets/macro_palette.json: a larger room palette in the
style of macro_dense (rooms only, A-A doors, walls flush), with several door
layouts per room size.  Each layout puts at most one door per side, at a
random non-corner offset (doors on 2..4 sides); layouts equal up to the
size's own rotations are redrawn.  Weights: as macro_dense, split over the
layouts of a size.  Env: LAYOUTS (per size, default 3), SEED."""
import json, os
import numpy as np

SIZES = {"hall": (13, 13, 1.0), "long": (9, 16, 1.0), "wide": (11, 15, 1.0), "square": (10, 10, 1.0),
         "room": (9, 11, 1.0), "pass": (9, 9, 0.7), "mid": (9, 13, 0.7), "block": (11, 11, 0.7)}
LAYOUTS = int(os.environ.get("LAYOUTS", 3))
rng = np.random.default_rng(int(os.environ.get("SEED", 0)))


def grid(h, w, doors):
    g = np.full((h, w), "#")
    g[1:-1, 1:-1] = "."
    for d, i in doors:                                      # d: N E S W, i: offset along the side
        y, x = ((0, i), (i, w - 1), (h - 1, i), (i, 0))[d]
        g[y, x] = "A"
    return g


def canon(g):
    return min("".join(np.rot90(g, r).ravel()) for r in range(4) if np.rot90(g, r).shape == g.shape)


comps = {}
for name, (h, w, wt) in SIZES.items():
    seen = set()
    while len(seen) < LAYOUTS:
        nd = rng.choice([2, 3, 4], p=[0.3, 0.4, 0.3])
        sides = rng.choice(4, nd, replace=False)
        doors = [(d, int(rng.integers(1, (w if d % 2 == 0 else h) - 1))) for d in sides]
        g = grid(h, w, doors)
        c = canon(g)
        if c in seen:
            continue
        seen.add(c)
        comps[f"{name}{len(seen)}"] = {"weight": wt / LAYOUTS, "rows": ["".join(r) for r in g]}
comment = ("Generated by notes/experiments/macro_palette_gen.py: macro_dense-style rooms, "
           f"{LAYOUTS} random door layouts per size (one door per side at most).")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "castlegen", "tilesets",
                   "macro_palette.json")
with open(out, "w") as f:
    f.write("{\n" + f'  "comment": {json.dumps(comment)},\n  "compat": [["A", "A"]],\n  "components": {{\n')
    f.write(",\n".join(f'    "{n}": {{"kind": "room", "weight": {c["weight"]:.3g}, "rows": [\n      '
                       + ",\n      ".join(json.dumps(r) for r in c["rows"]) + "]}" for n, c in comps.items()))
    f.write("\n  }\n}\n")
print(len(comps), "families ->", os.path.normpath(out))
